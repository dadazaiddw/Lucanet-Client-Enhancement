import java.lang.reflect.*;
import java.nio.file.*;
import java.security.*;
import java.util.*;

/** Compare the real native compile entry with and without the enhancement agent. */
public final class NativeCompilerIsolationProbe {
    public static void main(String[] args)throws Exception {
        Class<?> compilerType=Class.forName("com.lucanet.lisa.util.compiler.DynamicCompiler");
        boolean baseline=Boolean.getBoolean("fixture.baseline");
        if(!baseline){
            Class<?> bridge=Class.forName("cn.lucanet.enhancement.exit.LiveBridge",false,null);
            Field current=bridge.getDeclaredField("current");current.setAccessible(true);Object module=current.get(null);
            Object transformer=module.getClass().getMethod("transformer").invoke(module);
            Class<?> type=transformer.getClass();Method target=type.getDeclaredMethod("isTarget",String.class);target.setAccessible(true);
            String name=compilerType.getName().replace('.','/');
            check(!Boolean.TRUE.equals(target.invoke(null,name)),"native compiler is not an enhancement target");
            byte[] bytes;try(java.io.InputStream in=compilerType.getResourceAsStream("DynamicCompiler.class")){bytes=in.readAllBytes();}
            check(((java.lang.instrument.ClassFileTransformer)transformer).transform(compilerType.getModule(),compilerType.getClassLoader(),name,null,null,bytes)==null,"native compiler bytecode is untouched");
            for(String removed:List.of("JavaLombok","LombokCompiler","LombokLibrary"))
                check(type.getClassLoader().getResource("cn/lucanet/enhancement/exit/"+removed+".class")==null,"removed support class: "+removed);
        }
        Constructor<?> ctor=compilerType.getDeclaredConstructor();ctor.setAccessible(true);Object compiler=ctor.newInstance();
        Class<?> unitType=Class.forName("com.lucanet.lisa.util.compiler.CompilationUnit"),providerType=Class.forName("com.lucanet.lisa.util.compiler.ModuleInfoProvider");
        StringBuilder result=new StringBuilder();
        for(boolean explicit:List.of(false,true)){
            Object provider=Proxy.newProxyInstance(providerType.getClassLoader(),new Class<?>[]{providerType},(proxy,method,values)->{
                switch(method.getName()){
                    case "getModuleName":return "fixture.nativecheck";
                    case "getModulePathArguments":return explicit?List.of("-proc:none"):List.of();
                    case "getRequiredModuleNames":return List.of();
                    default:throw new UnsupportedOperationException(method.getName());
                }
            });
            for(boolean valid:List.of(true,false)){
                Object unit=unitType.getConstructor(String.class,String.class).newInstance("Fixture","package fixture; @Deprecated public class Fixture { public int answer(){ return "+(valid?"42":"missing()")+"; } }");
                Object compilation=compilerType.getMethod("compile",List.class,boolean.class,List.class,providerType).invoke(compiler,List.of(unit),true,List.of(),provider);
                check(Boolean.valueOf(!valid).equals(compilation.getClass().getMethod("isError").invoke(compilation)),"native compiler returns expected success/error");
                result.append("explicit=").append(explicit).append(";valid=").append(valid).append('\n');
                Map<String,String> hashes=new TreeMap<>();
                Iterator<?> entries=(Iterator<?>)compilation.getClass().getMethod("getEntryIterator").invoke(compilation);
                while(entries.hasNext()){Map.Entry<?,?> entry=(Map.Entry<?,?>)entries.next();hashes.put(entry.getKey().toString(),Base64.getEncoder().encodeToString(MessageDigest.getInstance("SHA-256").digest((byte[])entry.getValue())));}
                result.append(hashes).append('\n');
                for(Object message:(List<?>)compilation.getClass().getMethod("getCompilerMessageList").invoke(compilation))
                    for(String getter:List.of("getType","getFileName","getStartPosition","getEndPosition","getLine","getColumn","getMessage"))
                        result.append(getter).append('=').append(message.getClass().getMethod(getter).invoke(message)).append('\n');
                check(!valid||!hashes.isEmpty(),"native compiler generated bytecode");
            }
        }
        Path evidence=Path.of(args[0]+".native.txt");
        if(baseline)Files.writeString(evidence,result);
        else check(Files.readString(evidence).contentEquals(result),"native bytecode and error diagnostics match the unenhanced baseline");
        System.out.println("PASS: "+(baseline?"native baseline recorded":"real DynamicCompiler.compile bytecode and diagnostics unchanged; default/explicit processor policy preserved; Lombok hooks absent"));
    }
    private static void check(boolean condition,String message){if(!condition)throw new AssertionError(message);}
}
